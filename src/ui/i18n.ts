export type Lang = 'fr' | 'en';
const DICTS: Record<Lang, Record<Key, string>> = { fr, en };

/** Langues proposées dans les réglages (libellé dans sa propre langue). */
export const LANGS: readonly { id: Lang; label: string }[] = [
  { id: 'fr', label: 'Français' },
  { id: 'en', label: 'English' },
];

let current: Lang = 'fr';

export const getLang = (): Lang => current;
export const isLang = (v: unknown): v is Lang => typeof v === 'string' && v in DICTS;

export function setLang(l: Lang): void {
  current = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l;
}

/** Texte traduit ; `{nom}` est remplacé par `vars.nom`. Repli sur le français puis sur la clé. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[current][key] ?? fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Texte d'une clé dynamique (arme, aide…) : null si la clé n'existe pas. */
export function tKey(key: string, vars?: Record<string, string | number>): string | null {
  return key in fr ? t(key as Key, vars) : null;
}

/** Noms d'équipe par défaut dans la langue courante. */
export const defaultTeamNames = (): string[] => [0, 1, 2, 3].map((i) => t(`team.default.${i}` as Key));

export const DICTIONARIES = DICTS;
